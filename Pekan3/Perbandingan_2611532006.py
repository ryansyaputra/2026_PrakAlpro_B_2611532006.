# Nama variabel ditambah 4 digit nim terakhir contoh: angka_2006
# Program ini menggunakan funsgi input()
# Program operator perbandingan dalam python

angka1_2006 = int(input("Input angka-1: "))
angka2_2006 = int(input("Input angka-2: "))

# Lebih besar dari
hasil_2006 = angka1_2006 > angka2_2006
print("\nOperator lebih besar dari")
print("angka1 > angka2 =", hasil_2006)

# Lebih kecil dari
hasil_2006 = angka1_2006 < angka2_2006
print("\nOperator lebih kecil dari")
print("angka1 < angka2 =", hasil_2006)

# Lebih besar dari atau sama dengan
hasil_2006 = angka1_2006 >= angka2_2006
print("\nOperator lebih besar dari atau sama dengan")
print("angka1 >= angka2 =", hasil_2006)

# Lebih kecil dari atau sama dengan
hasil_2006 = angka1_2006 <= angka2_2006
print("\nOperator lebih kecil dari atau sama dengan")
print("angka1 <= angka2 =", hasil_2006)

# Sama dengan
hasil_2006 = angka1_2006 == angka2_2006
print("\nOperator Sama dengan")
print("angka1 == angka2 =", hasil_2006)

# Tidak sama dengan
hasil_2006 = angka1_2006 != angka2_2006
print("\nOperator Tidak sama dengan")
print("angka1 != angka2 =", hasil_2006)

# Tambahan : Perbandingan berantai dalam python
hasil_2006 = 0 < angka1_2006 < 100
print("\nOperator Perbandingan berantai")
print("0 < angka1 < 100 =", hasil_2006)

hasil_2006 = 0 < angka2_2006 < 100
