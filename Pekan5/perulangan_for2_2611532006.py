# Buat program untuk perulangan for dalam Python
# Nama variabel ditambah 4 digit nim terakhir contoh: ulang_2006
# Program ini menggunakan fungsi input()

ulang_2006 = int(input("Masukkan jumlah perulangan: "))
print("Perulangan ke-0 sampai ke-", ulang_2006-1)
for i_2006 in range(ulang_2006):
    print(i_2006, end=" ")
print()
print("Perulangan ke-1 sampai ke-", ulang_2006)
for i_2006 in range(1, ulang_2006 + 1):
    print(i_2006, end=" ")